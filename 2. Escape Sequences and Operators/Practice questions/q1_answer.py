#take 2 numbers as input from user and print their sum, diff, product and remainder


a = int(input("Enter 1st Number ="))
b = int(input("Enter 2nd Number ="))

sum = (a+b)
difference = (a-b)
product = (a * b)
remainder = (a % b)

print(f"Sum = {sum}")
print(f"difference = {difference}")
print(f"product = {product}")
print(f"remainder = {remainder}")